POS = {}  # name -> (u, v, w, h)


def load():
    img = pyxel.images[0]
    for i, (name, rows) in enumerate(SPR16.items()):
        u, v = (i % 16) * 16, (i // 16) * 16
        img.set(u, v, rows)
        POS[name] = (u, v, 16, 16)
    for i, (name, rows) in enumerate(SPR8.items()):
        u, v = (i % 32) * 8, 128 + (i // 32) * 8
        img.set(u, v, rows)
        POS[name] = (u, v, 8, 8)


def draw(name, x, y, flip=False, rotate=0.0, scale=1.0):
    """Draw sprite centred on (x, y)."""
    u, v, w, h = POS[name]
    pyxel.blt(x - w / 2, y - h / 2, 0, u, v, -w if flip else w, h, 0, rotate, scale)
